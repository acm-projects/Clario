const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
  try {
    const context = await browser.newContext({ permissions: ['microphone', 'camera'] });
    const page = await context.newPage();
    page.on('dialog', dialog => dialog.accept());
    const base = process.env.CLARIO_TEST_URL || 'http://127.0.0.1:5173';
    const id = 'b8c0ab0d-056c-46b2-8892-7a043d85f310';
    let runCount = 0, finishCount = 0, generateCount = 0, saved = false;
    let evidence;
    await page.route('**/node_modules/.vite/deps/@elevenlabs_client.js*', route => route.fulfill({ contentType: 'application/javascript', body: `export const Conversation = { startSession: async options => {
      if (options.overrides?.agent?.firstMessage !== undefined) throw new Error("Override for field 'first_message' is not allowed by config.");
      for (const name of ['repo_name', 'bug_summary']) {
        if (!options.dynamicVariables?.[name]) throw new Error('Missing required dynamic variable: ' + name);
      }
      window.__voiceStarts = (window.__voiceStarts || 0) + 1;
      window.__voiceOptions = options;
      window.__voiceTest = { contexts: [], cues: [] };
      options.onMessage({ source: 'user', message: 'I checked the boundary condition and chose a hash table.' });
      options.onModeChange({ mode: 'listening' });
      return { sendContextualUpdate: text => window.__voiceTest.contexts.push(text), sendUserMessage: text => window.__voiceTest.cues.push(text), getInputVolume: () => 0, endSession: async () => options.onDisconnect() };
    }};` }));
    await page.route('**/__dev/profile', route => route.fulfill({ json: { user: { id: 'submit-test', email: 'submit@example.test' }, profile: { id: 'submit-test', display_name: 'Submit Tester', assessment_completed: true, starting_difficulty: 'Medium' } } }));
    await page.route('**/voice/*session*', route => route.fulfill({ json: { signed_url: 'wss://example.test', variables: { problem_title: 'Example', problem_description: 'Investigate.', repo_name: 'Example', bug_summary: 'Investigate.' } } }));
    await page.route('**/api/repo-challenges/example?*', route => route.fulfill({ json: { id: 'example', title: 'Example repository', difficulty: 'Easy', language: 'python', category: 'Debugging', estimatedMinutes: 20, description: 'Investigate.', objective: 'Fix the bug.', expectedBehavior: 'Correct output.', constraints: [], entrypoint: 'main.py', files: [{ path: 'main.py', content: 'print(1)', language: 'python', readOnly: false }] } }));
    await page.route('**/api/repo-challenges/example/run', route => {
      runCount++;
      if (runCount === 1) return route.fulfill({json:{success:false,passed:1,failed:1,total:2,not_run:0,tests:[{name:'test_basic',passed:true},{name:'test_boundary',passed:false,status:'failed',message:'AssertionError: expected 2, received 1'}],error:null}});
      if (runCount === 2) return route.fulfill({status:503,json:{detail:'Code execution is unavailable.'}});
      return route.fulfill({json:{success:true,passed:2,failed:0,total:2,not_run:0,tests:[{name:'test_basic',passed:true},{name:'test_boundary',passed:true}],error:null}});
    });
    await page.route('**/api/repo-challenges/example/finish', route => {
      finishCount++; evidence = route.request().postDataJSON();
      assert.equal(evidence.files['main.py'], 'print(1)');
      assert.equal(evidence.transcript[0].source, 'user');
      assert.equal(evidence.communication, null);
      assert.ok(evidence.duration_seconds > 0);
      assert.equal(evidence.run_events.length,6);
      assert.equal(evidence.run_events[3].phase,'unavailable');
      assert.ok(evidence.transcript[0].elapsed_seconds >= 0);
      assert.ok(Number.isFinite(Date.parse(evidence.transcript[0].received_at)));
      return route.fulfill({ json: { saved: true, submission_id: id, message: 'Saved' } });
    });
    const session = { id, status: 'completed', ended_at: '2026-10-30T18:00:00Z' };
    const feedback = { id, technical_score: 60, reasoning_score: 65, communication_score: 70, overall_score: 65, strengths: ['Scoped change'], weaknesses: ['Missing validation'], recommendations: ['Check edge cases'], report: { summary: 'Your interview was reviewed.', technique_gaps: [{ technique: 'Boundary checks', evidence: 'One boundary was omitted.', practice: 'Try empty and single-item inputs.' }], communication_metrics: { monitored_seconds: 5, silent_seconds: 3, silence_percent: 60, longest_pause_seconds: 3, filler_count: null, words_per_speaking_minute: null, limitations: ['Approximate volume observations.'], silence_intervals: [{ start_seconds: 1, end_seconds: 4, duration_seconds: 3 }] } } };
    await page.route(`**/api/feedback/${id}`, route => {
      if (route.request().method() === 'GET') return route.fulfill({ json: { session, problem: { title: 'Example repository' }, feedback: saved ? feedback : null } });
      generateCount++; saved = true; return route.fulfill({ json: feedback });
    });
    await page.route('**/api/sessions/*/transcript', route => route.fulfill({ json: [{speaker: 'user', text: 'I chose a hash table.', received_at: '2026-11-02T18:00:00Z', elapsed_seconds: 2.5}] }));
    await page.goto(`${base}/interview/repo/example`);
    await page.waitForFunction(() => window.__voiceStarts === 1);
    assert.equal(await page.evaluate(() => window.__voiceOptions.overrides?.agent?.firstMessage), undefined);
    assert.equal(await page.getByRole('button', { name: 'Start interview', exact: true }).count(), 0);
    await page.waitForFunction(() => window.__voiceOptions && window.__voiceStarts > 0);
    await page.getByRole('button', {name:'Run Tests',exact:true}).click();
    await page.getByText('AssertionError: expected 2, received 1',{exact:true}).waitFor();
    await page.getByText('1/2 unit tests passed.',{exact:false}).waitFor();
    await page.getByRole('button', {name:'Run Tests',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'Code execution is unavailable.'}).waitFor();
    await page.getByRole('button', {name:'Run Tests',exact:true}).click();
    await page.getByText('Starter code tested. No code changes submitted.',{exact:true}).waitFor();
    assert.equal(await page.getByText('Already passing in starter',{exact:true}).count(),2);
    assert.equal(await page.locator('li').filter({hasText:'Already passing in starter'}).first().locator('span').first().innerText(),'\u2022');
    assert.equal(runCount,3);
    const runs = await page.evaluate(() => window.__voiceTest.contexts.filter(text=>text.startsWith('Execution update')).map(text=>JSON.parse(text.slice(text.indexOf('\n')+1))));
    assert.deepEqual(runs.map(run=>run.phase),['running','completed','running','unavailable','running','completed']);
    assert.equal(runs[1].files['main.py'],'print(1)');
    assert.equal(runs[1].result.failed,1);
    assert.equal(runs[1].result.starter_unchanged,true);
    assert.match(runs[3].result.error,/unavailable/);
    await page.evaluate(() => window.__voiceOptions.onError('Connection lost'));
    await page.waitForFunction(() => window.__voiceStarts === 2);
    assert.match((await page.evaluate(() => window.__voiceTest.contexts)).join(' '), /Resume this ongoing interview/);
    assert.match((await page.evaluate(() => window.__voiceTest.contexts)).join(' '), /AssertionError: expected 2, received 1/);
    await page.getByRole('button', {name:'Submit',exact:true}).click();
    await page.getByText('Final code submitted. Follow-up questions are now in progress.').waitFor();
    const review = await page.evaluate(() => window.__voiceTest);
    assert.equal(review.cues.length,1);
    assert.match(review.cues[0],/Begin the follow-up questioning now/);
    assert.equal(await page.getByRole('button',{name:'Submitted',exact:true}).isDisabled(),true);
    assert.equal(await page.getByRole('button',{name:'Run Tests',exact:true}).isDisabled(),true);
    assert.equal(await page.getByRole('button',{name:'Reset files',exact:true}).first().isDisabled(),true);
    assert.equal(runCount,3); assert.equal(finishCount,0); assert.equal(generateCount,0);
    await page.waitForTimeout(1400);
    await page.getByRole('button', { name: 'End interview', exact: true }).click();
    await page.waitForURL(`**/report/${id}`);
    await page.getByText('Your interview was reviewed.', { exact: true }).waitFor();
    await page.getByText('Session transcript', { exact: true }).click();
    const downloadReady = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download transcript', exact: true }).click();
    assert.equal((await downloadReady).suggestedFilename(), `interview-${id}-transcript.txt`);
    assert.equal(await page.getByRole('heading', { name: 'Speech observations', exact: true }).count(), 0);
    await page.getByRole('heading', { name: 'Your UMPIRE breakdown', exact: true }).waitFor();
    assert.equal(finishCount, 1); assert.equal(generateCount, 1);
    await page.reload(); await page.getByText('Your interview was reviewed.', { exact: true }).waitFor();
    assert.equal(generateCount, 1);
    await page.route('**/api/problems', route => route.fulfill({ status: 503, json: { detail: 'Problem service unavailable' } }));
    await page.goto(`${base}/interview?mode=recommended`);
    await page.getByRole('heading', { name: 'Two Sum', exact: true }).waitFor();
    const codingId = '390d0554-8f0b-435b-95f6-6c1071c48299';
    const calls = [];
    await page.route('**/api/problems/two-sum', route => route.fulfill({ json: { slug: 'two-sum', title: 'Two Sum', difficulty: 'Easy', topics: [], description_html: '<p>Find two indices.</p>', starter_code: { python3: 'class Solution: pass' }, example_testcases: '' } }));
    await page.route('**/api/sessions', route => { calls.push('create'); return route.fulfill({ json: { id: codingId, problem_slug: 'two-sum', language: 'python3', status: 'in_progress' } }); });
    await page.route(`**/api/sessions/${codingId}/snapshots`, route => { calls.push('snapshot'); assert.equal(route.request().postDataJSON().code, 'class Solution: pass'); return route.fulfill({ json: {} }); });
    await page.route(`**/api/sessions/${codingId}/evidence`, route => { calls.push('evidence'); assert.equal(route.request().postDataJSON().transcript[0].source, 'user'); return route.fulfill({ json: { saved: true } }); });
    await page.route(`**/api/sessions/${codingId}/end`, route => { calls.push('end'); return route.fulfill({ json: { id: codingId, status: 'completed' } }); });
    await page.route(`**/api/feedback/${codingId}`, route => {
      if (route.request().method() === 'GET') return route.fulfill({ json: { session: { ...session, id: codingId }, problem: { title: 'Two Sum' }, feedback: null } });
      calls.push('generate'); return route.fulfill({ json: feedback });
    });
    await page.route('**/run/tests', route => { calls.push('run'); return route.fulfill({json:{status:'Runtime Error',passed:0,total:1,cases:[],stdout:'',error:'ValueError: coding fixture failure'}}); });
    await page.goto(`${base}/interview/two-sum`);
    await page.waitForFunction(() => window.__voiceOptions && window.__voiceStarts > 0);
    await page.getByRole('button',{name:'Run Tests',exact:true}).click();
    await page.getByText('ValueError: coding fixture failure',{exact:true}).waitFor();
    const codingRuns = await page.evaluate(() => window.__voiceTest.contexts.filter(text=>text.startsWith('Execution update')).map(text=>JSON.parse(text.slice(text.indexOf('\n')+1))));
    assert.equal(codingRuns[1].files['main.py'],'class Solution: pass');
    assert.equal(codingRuns[1].result.error,'ValueError: coding fixture failure');
    await page.getByRole('button', { name: 'Submit', exact: true }).click();
    await page.getByText('Final code submitted. Follow-up questions are now in progress.').waitFor();
    assert.equal(await page.getByRole('button',{name:'Submitted',exact:true}).isDisabled(),true);
    assert.deepEqual(calls, ['create', 'snapshot', 'run', 'snapshot']);
    assert.match(page.url(), /interview\/two-sum/);
    await page.getByRole('button', { name: 'End interview', exact: true }).click();
    await page.waitForURL(`**/report/${codingId}`);
    await page.getByText('Your interview was reviewed.', { exact: true }).waitFor();
    assert.deepEqual(calls, ['create', 'snapshot', 'run', 'snapshot', 'snapshot', 'evidence', 'end', 'generate']);
    await page.goto(`${base}/interview/repo/example`);
    await page.getByText('Listening...', { exact: false }).count();
    await page.waitForFunction(() => window.__voiceOptions && window.__voiceStarts === 1);
    await page.getByRole('button',{name:'Submit',exact:true}).click();
    await page.getByRole('button',{name:'Submitted',exact:true}).waitFor();
    await page.reload();
    await page.getByRole('button',{name:'Submitted',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Submitted',exact:true}).isDisabled(),true);
    await page.waitForFunction(() => window.__voiceOptions && window.__voiceStarts === 1);
    assert.equal(await page.evaluate(() => window.__voiceTest.cues.length),0);
    assert.match((await page.evaluate(() => window.__voiceTest.contexts)).join(' '),/final submission has already happened/);
    await page.evaluate(() => window.__voiceOptions.onDisconnect({ reason: 'error', message: 'Voice API quota exceeded', context: {} }));
    await page.getByText('Voice API quota exceeded', { exact: true }).waitFor();
    await page.waitForTimeout(1600);
    assert.equal(await page.evaluate(() => window.__voiceStarts), 1);
    assert.equal(await page.getByRole('button', { name: 'Retry connection', exact: true }).count(), 0);
    console.log('PASS: Piston run results and outages reach the interviewer and survive reconnect; Submit locks once and starts questions; End Call saves timed transcript and generates the detailed report; reload reuses feedback.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
