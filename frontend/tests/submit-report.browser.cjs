const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
  try {
    const context = await browser.newContext({ permissions: ['microphone', 'camera'] });
    const page = await context.newPage();
    page.on('dialog', dialog => dialog.accept());
    const base = process.env.CLARIO_TEST_URL || 'http://127.0.0.1:5173';
    const id = 'b8c0ab0d-056c-46b2-8892-7a043d85f310';
    let runCount = 0, finishCount = 0, generateCount = 0, saved = false;
    let evidence;
    await page.route('**/node_modules/.vite/deps/@elevenlabs_client.js*', route => route.fulfill({ contentType: 'application/javascript', body: `export const Conversation = { startSession: async options => {
      window.__voiceStarts = (window.__voiceStarts || 0) + 1;
      window.__voiceOptions = options;
      window.__voiceTest = { contexts: [], cues: [] };
      options.onMessage({ source: 'user', message: 'I checked the boundary condition and chose a hash table.' });
      options.onModeChange({ mode: 'listening' });
      return { sendContextualUpdate: text => window.__voiceTest.contexts.push(text), sendUserMessage: text => window.__voiceTest.cues.push(text), getInputVolume: () => 0, endSession: async () => options.onDisconnect() };
    }};` }));
    await page.route('**/__dev/profile', route => route.fulfill({ json: { user: { id: 'submit-test', email: 'submit@example.test' }, profile: { id: 'submit-test', display_name: 'Submit Tester', assessment_completed: true, starting_difficulty: 'Medium' } } }));
    await page.route('**/voice/*session*', route => route.fulfill({ json: { signed_url: 'wss://example.test', variables: { problem_title: 'Example', problem_description: 'Investigate.' } } }));
    await page.route('**/api/repo-challenges/example', route => route.fulfill({ json: { id: 'example', title: 'Example repository', difficulty: 'Easy', language: 'python', category: 'Debugging', estimatedMinutes: 20, description: 'Investigate.', objective: 'Fix the bug.', expectedBehavior: 'Correct output.', constraints: [], entrypoint: 'main.py', files: [{ path: 'main.py', content: 'print(1)', language: 'python', readOnly: false }] } }));
    await page.route('**/api/repo-challenges/example/run', route => { runCount++; return route.fulfill({ json: { success: true, passed: 1, failed: 0, total: 1, tests: [], error: null } }); });
    await page.route('**/api/repo-challenges/example/finish', route => {
      finishCount++; evidence = route.request().postDataJSON();
      assert.equal(evidence.files['main.py'], 'print(1)');
      assert.equal(evidence.transcript[0].source, 'user');
      assert.ok(evidence.communication.silence_intervals.length > 0);
      return route.fulfill({ json: { saved: true, submission_id: id, message: 'Saved' } });
    });
    const session = { id, status: 'completed', ended_at: '2026-10-30T18:00:00Z' };
    const feedback = { id, technical_score: 60, reasoning_score: 65, communication_score: 70, overall_score: 65, strengths: ['Scoped change'], weaknesses: ['Missing validation'], recommendations: ['Check edge cases'], report: { summary: 'Your interview was reviewed.', technique_gaps: [{ technique: 'Boundary checks', evidence: 'One boundary was omitted.', practice: 'Try empty and single-item inputs.' }], communication_metrics: { monitored_seconds: 5, silent_seconds: 3, silence_percent: 60, longest_pause_seconds: 3, filler_count: null, words_per_speaking_minute: null, limitations: ['Approximate volume observations.'], silence_intervals: [{ start_seconds: 1, end_seconds: 4, duration_seconds: 3 }] } } };
    await page.route(`**/api/feedback/${id}`, route => {
      if (route.request().method() === 'GET') return route.fulfill({ json: { session, problem: { title: 'Example repository' }, feedback: saved ? feedback : null } });
      generateCount++; saved = true; return route.fulfill({ json: feedback });
    });
    await page.goto(`${base}/interview/repo/example`);
    await page.waitForFunction(() => window.__voiceStarts === 1);
    assert.equal(await page.getByRole('button', { name: 'Start interview', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Submit', exact: true }).click();
    await page.getByText('Code sent to the duck for review. Your interview is still in progress.').waitFor();
    assert.equal(runCount, 0); assert.equal(finishCount, 0); assert.equal(generateCount, 0);
    assert.match(page.url(), /interview\/repo\/example/);
    const review = await page.evaluate(() => window.__voiceTest);
    assert.match(review.contexts[0], /print\(1\)/); assert.equal(review.cues.length, 1);
    assert.equal(await page.evaluate(() => window.__voiceStarts), 1);
    await page.evaluate(() => window.__voiceOptions.onError('Connection lost'));
    await page.getByRole('button', { name: 'Retry connection', exact: true }).click();
    await page.waitForFunction(() => window.__voiceStarts === 2);
    assert.match((await page.evaluate(() => window.__voiceTest.contexts)).join(' '), /Resume this ongoing interview/);
    await page.getByRole('button', { name: 'Run Tests', exact: true }).click();
    await page.getByText('All behavior checks passed.', { exact: true }).waitFor();
    assert.equal(runCount, 1); assert.equal(finishCount, 0);
    await page.waitForTimeout(1400);
    await page.getByRole('button', { name: 'End interview', exact: true }).click();
    await page.waitForURL(`**/report/${id}`);
    await page.getByText('Your interview was reviewed.', { exact: true }).waitFor();
    await page.getByRole('heading', { name: 'Recorded silence moments', exact: true }).waitFor();
    await page.getByText('View 1 pauses of at least one second').click();
    await page.getByText(/0:01.*0:04.*3.0s quiet/).waitFor();
    await page.getByRole('heading', { name: 'Coding techniques to practice', exact: true }).waitFor();
    assert.equal(finishCount, 1); assert.equal(generateCount, 1);
    await page.reload(); await page.getByText('Your interview was reviewed.', { exact: true }).waitFor();
    assert.equal(generateCount, 1);
    await page.route('**/api/problems', route => route.fulfill({ status: 503, json: { detail: 'Problem service unavailable' } }));
    await page.goto(`${base}/interview?mode=recommended`);
    await page.getByRole('heading', { name: 'Two Sum', exact: true }).waitFor();
    const codingId = '390d0554-8f0b-435b-95f6-6c1071c48299';
    const calls = [];
    await page.route('**/api/problems/two-sum', route => route.fulfill({ json: { slug: 'two-sum', title: 'Two Sum', difficulty: 'Easy', topics: [], description_html: '<p>Find two indices.</p>', starter_code: { python3: 'class Solution: pass' }, example_testcases: '' } }));
    await page.route('**/api/sessions', route => { calls.push('create'); return route.fulfill({ json: { id: codingId, problem_slug: 'two-sum', language: 'python3', status: 'in_progress' } }); });
    await page.route(`**/api/sessions/${codingId}/snapshots`, route => { calls.push('snapshot'); assert.equal(route.request().postDataJSON().code, 'class Solution: pass'); return route.fulfill({ json: {} }); });
    await page.route(`**/api/sessions/${codingId}/evidence`, route => { calls.push('evidence'); assert.equal(route.request().postDataJSON().transcript[0].source, 'user'); return route.fulfill({ json: { saved: true } }); });
    await page.route(`**/api/sessions/${codingId}/end`, route => { calls.push('end'); return route.fulfill({ json: { id: codingId, status: 'completed' } }); });
    await page.route(`**/api/feedback/${codingId}`, route => {
      if (route.request().method() === 'GET') return route.fulfill({ json: { session: { ...session, id: codingId }, problem: { title: 'Two Sum' }, feedback: null } });
      calls.push('generate'); return route.fulfill({ json: feedback });
    });
    await page.goto(`${base}/interview/two-sum`);
    await page.getByRole('button', { name: 'Submit', exact: true }).click();
    await page.getByText('Code sent to the duck for review. Your interview is still in progress.').waitFor();
    assert.deepEqual(calls, []);
    assert.match(page.url(), /interview\/two-sum/);
    await page.getByRole('button', { name: 'End interview', exact: true }).click();
    await page.waitForURL(`**/report/${codingId}`);
    await page.getByText('Your interview was reviewed.', { exact: true }).waitFor();
    assert.deepEqual(calls, ['create', 'snapshot', 'evidence', 'end', 'generate']);
    console.log('PASS: Submit cues duck without tests or navigation; Run Tests executes; End Call saves transcript/silence and generates the detailed report; reload reuses feedback.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
